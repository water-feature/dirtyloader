"""
Build the mod shop's files: every mod in meta.json, compiled for each target, into site/shop/mods/<target>/<id>.m8x,
and site/shop/catalog.json (what the page lists, with each file's sha256, size and hooks). Also font.js, the 5 x 7
pixel font from dl/pixui.h, so the page's M8 screens use the same letters as core's own pages.

    python site/shop/make_shop.py

Needs the ARM compiler (dirtyloader.cc). No firmware is read or written: a .m8x holds only the mod's own code.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)

from dirtyloader import cc  # noqa: E402

SDK = os.path.join(ROOT, "dirtyloader", "sdk", "include", "dl")


def event_names() -> dict:
    text = open(os.path.join(SDK, "mod.h"), encoding="utf-8").read()
    return {int(v, 16): n[3:].lower() for n, v in re.findall(r"\b(EV_[A-Z0-9_]+)\s*=\s*(0x[0-9A-Fa-f]+)", text)}


def write_font(path: str) -> None:
    text = open(os.path.join(SDK, "pixui.h"), encoding="utf-8").read()
    chars = re.search(r'pui_chars\[\]\s*=\s*"([^"]+)"', text).group(1)
    body = text[text.index("pui_glyphs[][7]"):]
    body = body[body.index("{") + 1:body.index("};")]
    rows = [[int(x, 16) for x in g.split(",")] for g in re.findall(r"\{([^{}]+)\}", body)]
    assert len(rows) == len(chars), (len(rows), len(chars))
    glyphs = {c: r for c, r in zip(chars, rows)}
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by make_shop.py from dl/pixui.h: core's 5 x 7 font, a row a number (bit 4 leftmost).\n")
        f.write("export const FONT = " + json.dumps(glyphs, separators=(",", ":")) + ";\n")


def main() -> int:
    meta = json.load(open(os.path.join(HERE, "meta.json"), encoding="utf-8"))
    names = event_names()
    out_mods = []
    default_targets = [target for target, info in meta["targets"].items() if "events" not in info]
    for m in meta["mods"]:
        builds = {}
        for tid in m.get("targets", default_targets):
            srcs = [os.path.join(ROOT, s) for s in m["sources"]]
            try:
                blob, info = cc.build_target(srcs, tid)
            except cc.CCError as e:
                print(f"  {m['id']} for {tid}: not built ({str(e).splitlines()[0][:100]})")
                continue
            p = cc.parse_m8x(blob)
            if p["id"] != m["id"]:
                raise SystemExit(f"{m['sources']} builds {p['id']}, meta.json says {m['id']}")
            rel = f"mods/{tid}/{m['id']}.m8x"
            os.makedirs(os.path.join(HERE, "mods", tid), exist_ok=True)
            with open(os.path.join(HERE, rel), "wb") as f:
                f.write(blob)
            builds[tid] = {
                "file": rel, "size": len(blob), "sha256": hashlib.sha256(blob).hexdigest(), "fw": p["fw"],
                "version": p["version"],
            }
            hooks = sorted({names.get(s["event"], hex(s["event"])) for s in p["subscribe"]})
            version, mtitle = p["version"], p["title"]
        if not builds:
            print(f"  {m['id']}: no build, left out")
            continue
        entry = {k: v for k, v in m.items() if k not in ("sources", "targets")}
        entry.update(version=version, header_title=mtitle, hooks=hooks, builds=builds,
                     source="https://github.com/irpina/dirtyloader/tree/main/" + os.path.dirname(m["sources"][0]))
        out_mods.append(entry)
        print(f"  {m['id']} {version}: " + ", ".join(f"{t} {b['size']} B" for t, b in builds.items()))
    catalog = {
        "about": "Generated by make_shop.py from meta.json: do not edit. Each build is checked by its sha256 before "
                 "the page sends it to an M8.",
        "targets": meta["targets"], "categories": meta["categories"], "mods": out_mods,
    }
    with open(os.path.join(HERE, "catalog.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(catalog, f, indent=1)
        f.write("\n")
    write_font(os.path.join(HERE, "font.js"))
    print(f"catalog.json: {len(out_mods)} mods")
    return 0


if __name__ == "__main__":
    sys.exit(main())
